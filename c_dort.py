def errors_of(h):
    it=h["items"][-1]; out=[]; cur=None
    for b in it["blocks"]:
        if b["t"]!="p": continue
        x=strip(b["x"])
        m=re.match(r"错谬([一二三四五六七八九十]+)[：:]",x)
        if m: cur=[m.group(1),x,""]; out.append(cur)
        elif x.startswith("驳斥") and cur: cur[2]=x
    return out
ERR={h["num"]:errors_of(h) for h in _dt["heads"]}

