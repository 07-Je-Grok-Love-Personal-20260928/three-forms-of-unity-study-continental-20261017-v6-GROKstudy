_set=set(OWN); HIT={}
def _strip(t): return html.unescape(re.sub(r"<[^>]+>","",t))
def mark(h):
    def f(m):
        x=_strip(m.group(1))
        if x in _set:
            HIT[x]=HIT.get(x,0)+1
            return f'<span class="own" title="本站用语或本站翻译，不是 CCI 逐字引文">{m.group(1)}</span>'
        return m.group(0)
    return re.sub(r"“([^”]{1,200})”",f,h)
def check():
    miss=[x for x in OWN if x not in HIT]
    assert not miss, f"own 短语未出现：{miss}"
