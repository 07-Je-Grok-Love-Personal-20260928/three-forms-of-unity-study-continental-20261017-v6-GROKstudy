def _refs(doc,k):
    out=[]
    def walk(bl):
        for b in bl:
            if b["t"]=="ref": out.extend(b["x"])
    if k=="hc":
        for l in doc["lds"]: walk(l["blocks"])
    elif k=="bc":
        for a in doc["articles"]: walk(a["blocks"])
    else:
        for h in doc["heads"]:
            for i in h["items"]: walk(i["blocks"])
    return out
def scripture_stats():
    res={}
    for k in ("bc","hc","dort"):
        c=collections.Counter()
        for x in _refs(J(k),k):
            for m in _pat.finditer(x): c[m.group(1)]+=1
        res[k]=c
    return res
SS=scripture_stats()

def bars(rows,title):
    mx=max(v for _,v,_ in rows)
    out=f'<div class="bars reveal" role="img" aria-label="{title}"><p class="bt">{title}</p>'
    for lab,v,c in rows:
        out+=f'<div class="br"><span class="bl">{lab}</span><span class="bk"><i style="--w:{v/mx*100:.1f}%;--c:{c}"></i></span><b class="bv">{v}</b></div>'
    return out+'</div>'

